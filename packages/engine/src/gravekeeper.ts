import { getJson, HttpError } from "./http.js";
import { pullRequestFiles, RECIPES, resurrect } from "./recipes/index.js";
import { fetchRepoSources } from "./repoFiles.js";
import type { Resurrection } from "./schema.js";

/**
 * Gravekeeper: turns a curated Resurrection into a real pull request.
 * Guardrail: the ONLY writable repository is the sandbox below. Everything else gets the patch download.
 */
export const SANDBOX_REPO = "RamSuryaCH/revenant-crypt";
export const BRANCH_PREFIX = "revenant/";

export const isSandboxRepo = (repo: string) => repo.toLowerCase() === SANDBOX_REPO.toLowerCase();
export const branchFor = (recipeId: string) => `${BRANCH_PREFIX}${recipeId}`;

/** Local test evidence recorded by scripts/verify-crypt.mts (GitHub Actions is unavailable). */
export interface CryptVerification {
  repo: string;
  baseSha: string;
  node: string;
  generatedAt: string;
  baseline: { ok: boolean; summary: string };
  recipes: Record<string, { filesChanged: string[]; npmTest: { ok: boolean; summary: string }; differential: { ok: boolean; command: string; output: string } }>;
}

export interface OpenPrInput {
  repo: string;
  recipeId: string;
  token: string;
  verification?: CryptVerification | null;
  evidence?: string[];
  fromVersion?: string | null;
  /** Public URL of the app, linked from the PR body. */
  appUrl?: string;
  fetchImpl?: typeof fetch;
}

export interface OpenPrResult {
  url: string;
  number: number;
  branch: string;
  /** True when an already-open PR for this recipe was returned instead of opening a new one. */
  reused: boolean;
}

export class GravekeeperError extends Error {
  constructor(
    message: string,
    public status: number,
  ) {
    super(message);
  }
}

interface Pull {
  html_url: string;
  number: number;
}

export function prTitle(r: Pick<Resurrection, "package" | "replacement">): string {
  return `Resurrect ${r.package}: migrate to ${r.replacement}`;
}

const fence = (s: string) => `\`\`\`text\n${s.replace(/```/g, "'''").trim()}\n\`\`\``;

export function prBody(r: Resurrection, o: { baseSha: string; verification?: CryptVerification | null; appUrl?: string }): string {
  const v = o.verification && o.verification.baseSha === o.baseSha ? o.verification : null;
  const rv = v?.recipes[r.recipeId];
  const recipe = RECIPES[r.recipeId];
  const lines = [
    `Revenant found \`${r.package}\` in this repository's dependency graveyard and raised it as **${r.replacement}**.`,
    "",
    "## What this PR contains",
    "",
    ...r.files.map((f) => `- \`${f.path}\` (${f.kind === "add" ? "added" : "migrated"})`),
    `- \`.kiro/specs/${r.spec.slug}/\`: Kiro spec for this migration (EARS requirements, design, traced tasks)`,
    `- \`${r.tests.path}\`: differential property-based tests (fast-check), old package vs new code`,
    "",
    `Run the differential tests: \`npm install --no-save ${recipe?.testFile.deps.join(" ") ?? ""} && npx vitest run ${r.tests.path}\``,
    "",
    "## Test evidence",
    "",
  ];
  if (v && rv) {
    lines.push(
      `GitHub Actions is unavailable on this account (billing lock), so the suites were run locally on ${v.node} against base \`${v.baseSha.slice(0, 7)}\` with exactly the files in this PR (recorded ${v.generatedAt}).`,
      "",
      `**Sandbox suite before migration** (\`npm test\`): ${v.baseline.ok ? "pass" : "FAIL"}`,
      "",
      `**Sandbox suite after migration** (\`npm install && npm test\`): ${rv.npmTest.ok ? "pass" : "FAIL"}`,
      "",
      fence(rv.npmTest.summary),
      "",
      `**Differential tests** (\`${rv.differential.command}\`): ${rv.differential.ok ? "pass" : "FAIL"}`,
      "",
      fence(rv.differential.output),
    );
  } else {
    lines.push(`No recorded local run matches base \`${o.baseSha.slice(0, 7)}\`. Run \`npm install && npm test\` and the differential tests before merging.`);
  }
  lines.push("", "## Honest notes", "", ...(r.notes.length ? r.notes.map((n) => `- ${n}`) : ["- None."]));
  if (recipe) lines.push("", "## Limits of this recipe", "", ...recipe.limits.map((l) => `- ${l}`));
  lines.push("- `package-lock.json` is not regenerated by the Gravekeeper; run `npm install` to refresh it.");
  lines.push("", "---", `Opened by \`revenant gravekeeper ${r.recipeId}\`, run locally by the maintainer${o.appUrl ? ` (see it in the graveyard: ${o.appUrl})` : ""}. The Gravekeeper only writes to \`${SANDBOX_REPO}\`, on \`${BRANCH_PREFIX}*\` branches; the public web app is read-only.`);
  return `${lines.join("\n")}\n`;
}

/** Read-only: the open Gravekeeper PR for a recipe, or null. Works with a read token or none. */
export async function findResurrectionPr(recipeId: string, o: { token?: string; fetchImpl?: typeof fetch } = {}): Promise<OpenPrResult | null> {
  const branch = branchFor(recipeId);
  const owner = SANDBOX_REPO.split("/")[0]!;
  const headers: Record<string, string> = { "x-github-api-version": "2022-11-28", ...(o.token ? { authorization: `Bearer ${o.token}` } : {}) };
  const pulls = await getJson<Pull[]>(`https://api.github.com/repos/${SANDBOX_REPO}/pulls?state=open&head=${encodeURIComponent(`${owner}:${branch}`)}`, { headers, fetchImpl: o.fetchImpl, timeoutMs: 8000 });
  const pr = pulls?.[0];
  return pr ? { url: pr.html_url, number: pr.number, branch, reused: true } : null;
}

/** Open (or reuse) the pull request for one curated recipe on the sandbox repository. Local/maintainer use only. */
export async function openResurrectionPr(i: OpenPrInput): Promise<OpenPrResult> {
  if (!isSandboxRepo(i.repo)) throw new GravekeeperError(`The Gravekeeper only opens pull requests on ${SANDBOX_REPO}. Download the patch instead.`, 403);
  if (!Object.hasOwn(RECIPES, i.recipeId)) throw new GravekeeperError(`No curated recipe "${i.recipeId}".`, 400);
  const repo = SANDBOX_REPO;
  const branch = branchFor(i.recipeId);
  const api = `https://api.github.com/repos/${repo}`;
  const headers = { authorization: `Bearer ${i.token}`, "x-github-api-version": "2022-11-28" };
  const gh = <T>(path: string, method = "GET", body?: unknown) =>
    getJson<T>(`${api}${path}`, { method, headers, body: body === undefined ? undefined : JSON.stringify(body), fetchImpl: i.fetchImpl, timeoutMs: 15000 });
  const openPr = () => findResurrectionPr(i.recipeId, { token: i.token, fetchImpl: i.fetchImpl });

  // Idempotency: one open PR per recipe.
  const existing = await openPr();
  if (existing) return existing;

  const meta = await gh<{ default_branch: string }>("");
  if (!meta) throw new GravekeeperError(`${repo} is not reachable with the server token.`, 502);
  const base = meta.default_branch;
  const ref = await gh<{ object: { sha: string } }>(`/git/ref/heads/${encodeURIComponent(base)}`);
  if (!ref) throw new GravekeeperError(`Branch ${base} not found on ${repo}.`, 502);
  const baseSha = ref.object.sha;
  const baseCommit = await gh<{ tree: { sha: string } }>(`/git/commits/${baseSha}`);
  if (!baseCommit) throw new GravekeeperError("Base commit not found.", 502);

  const { files } = await fetchRepoSources(repo, { token: i.token, ref: baseSha, fetchImpl: i.fetchImpl });
  const r = resurrect({ recipeId: i.recipeId, files, evidence: i.evidence, fromVersion: i.fromVersion ?? null });
  if (r.files.length === 0) throw new GravekeeperError(`Nothing to migrate: no usage of ${r.package} found.`, 409);
  const out = pullRequestFiles(files, r);

  const tree = await gh<{ sha: string }>("/git/trees", "POST", { base_tree: baseCommit.tree.sha, tree: out.map((f) => ({ path: f.path, mode: "100644", type: "blob", content: f.content })) });
  const commit = await gh<{ sha: string }>("/git/commits", "POST", { message: `${prTitle(r)}\n\nGenerated by the Revenant Gravekeeper (recipe ${r.recipeId}).`, tree: tree!.sha, parents: [baseSha] });
  try {
    await gh("/git/refs", "POST", { ref: `refs/heads/${branch}`, sha: commit!.sha });
  } catch (e) {
    // Branch left over from a closed PR: move it to the fresh commit. Only revenant/* refs are ever touched.
    if (!(e instanceof HttpError && e.status === 422)) throw e;
    await gh(`/git/refs/heads/${branch}`, "PATCH", { sha: commit!.sha, force: true });
  }
  try {
    const pr = await gh<Pull>("/pulls", "POST", { title: prTitle(r), head: branch, base, body: prBody(r, { baseSha, verification: i.verification, appUrl: i.appUrl }), maintainer_can_modify: true });
    return { url: pr!.html_url, number: pr!.number, branch, reused: false };
  } catch (e) {
    // A concurrent request opened it first.
    const raced = e instanceof HttpError && e.status === 422 ? await openPr() : null;
    if (raced) return raced;
    throw e;
  }
}
