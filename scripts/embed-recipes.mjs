// Embeds recipe test files and the request shim into src/recipes/generated.ts as strings,
import process from "node:process";
// so the engine ships them without reading the filesystem. Run by the recipe-change hook.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "packages", "engine");
const read = (p) => readFileSync(join(root, "recipes", p), "utf8");
const entries = {
  MOMENT_TEST: "moment-to-dayjs/differential.test.ts",
  REQUEST_TEST: "request-to-fetch/differential.test.ts",
  REQUEST_SHIM: "request-to-fetch/request-compat.cjs",
  UUID_TEST: "uuid3-to-randomuuid/differential.test.ts",
};
let out = "// AUTO-GENERATED by scripts/embed-recipes.mjs. Do not edit; edit packages/engine/recipes/** instead.\n";
for (const [name, file] of Object.entries(entries)) out += `export const ${name} = ${JSON.stringify(read(file))};\n`;
writeFileSync(join(root, "src", "recipes", "generated.ts"), out);
process.stdout.write(`embedded ${Object.keys(entries).length} recipe files\n`);
