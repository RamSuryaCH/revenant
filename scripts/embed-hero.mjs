// Copies three tombstones from the precomputed sample into apps/web/src/data/hero-sample.ts,
// so the landing page paints real, cited data with no network call.
// Run: node scripts/embed-hero.mjs   (re-run after pnpm sample)
import { readFileSync, writeFileSync } from "node:fs";
import { stdout } from "node:process";

const sample = JSON.parse(readFileSync("apps/web/public/samples/cursed.scan.json", "utf8"));
const picks = ["request", "moment", "uuid"].map((n) => {
  const t = sample.tombstones.find((x) => x.name === n);
  if (!t) throw new Error(`sample has no tombstone ${n}`);
  return t;
});
const direct = sample.tombstones.filter((t) => t.direct);
const out = `// Generated by scripts/embed-hero.mjs from public/samples/cursed.scan.json. Do not edit by hand.
import type { Tombstone } from "@revenant/engine";

export const HERO_STONES: Tombstone[] = ${JSON.stringify(picks, null, 2)};

export const HERO_COUNTS = ${JSON.stringify({ direct: direct.length, badDirect: direct.filter((t) => t.status !== "living").length, total: sample.tombstones.length })} as const;
`;
writeFileSync("apps/web/src/data/hero-sample.ts", out);
stdout.write(`wrote hero-sample.ts: ${picks.map((p) => p.name).join(", ")}\n`);
